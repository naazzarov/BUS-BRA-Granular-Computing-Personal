"""Render the fold-level manuscript tables from aggregate output."""
import json
from pathlib import Path


HERE = Path(__file__).resolve().parent
MODELS = ("logistic", "gradient_boosting")
RULES = ("learned_margin", "learned_margin_gap")


def ranking_rows(aggregate):
    runs = [aggregate[model]["folds"] for model in MODELS]
    for logistic, boosting in zip(*runs, strict=True):
        keys = ("fold", "n", "n_malignant")
        if any(logistic[key] != boosting[key] for key in keys):
            raise ValueError("The backbones must use the same patient folds")
        cells = [str(logistic[key]) for key in keys]
        for fold in (logistic, boosting):
            baseline, augmented = [fold["augrc"][rule] for rule in RULES]
            cells.extend((f"{100 * baseline:.3f}", f"{100 * (augmented - baseline):+.3f}"))
        yield " & ".join(cells)


def frozen_rows(aggregate):
    runs = [aggregate["threshold_replay"][model]["folds"] for model in MODELS]
    for logistic, boosting in zip(*runs, strict=True):
        keys = ("fold", "calibration_pairs")
        if any(logistic[key] != boosting[key] for key in keys):
            raise ValueError("The backbones must use the same calibration folds")
        cells = [str(logistic["fold"]), str(logistic["calibration_pairs"])]
        for fold in (logistic, boosting):
            for rule in RULES:
                metrics = fold["rules"][rule]
                cells.append(f"{metrics['accepted']}/{metrics['n']}")
        yield " & ".join(cells)


def main():
    ranking = json.loads((HERE / "results.json").read_text())
    frozen = json.loads((HERE / "extension_results.json").read_text())
    rows = {
        "rankingfoldrows": ranking_rows(ranking),
        "frozenfoldrows": frozen_rows(frozen),
    }
    lines = ["% Generated by render_tables.py from aggregate results."]
    for name, table_rows in rows.items():
        lines.append(r"\newcommand{" + "\\" + name + "}{%")
        lines.extend(row + r" \\" for row in table_rows)
        lines.append("}")
    (HERE / "manuscript/audit_tables.tex").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
